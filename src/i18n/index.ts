/**
 * Lightweight i18n — EN / AR / FR with full RTL support for Arabic.
 * Pure dictionary lookup; language persisted in localStorage.
 */
import { useSyncExternalStore } from 'react';

export type Lang = 'en' | 'ar' | 'fr';

const LS_KEY = 'ec-lang';
let current: Lang = 'en';
const listeners = new Set<() => void>();

if (typeof window !== 'undefined') {
  const saved = window.localStorage.getItem(LS_KEY) as Lang | null;
  if (saved === 'en' || saved === 'ar' || saved === 'fr') current = saved;
}

export function getLang(): Lang {
  return current;
}

export function setLang(l: Lang): void {
  current = l;
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(LS_KEY, l);
    document.documentElement.lang = l;
    document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
  }
  listeners.forEach((fn) => fn());
}

export function subscribeLang(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** React hook: re-renders on language change. */
export function useLang(): Lang {
  return useSyncExternalStore(subscribeLang, getLang, () => 'en');
}

